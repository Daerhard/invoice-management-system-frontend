// ─── Section card ─────────────────────────────────────────────────────────────

interface SectionCardProps {
    section: SectionDef;
    positions: readonly EuerPosition[];
    published: boolean;
    euerId: number;
    onAddClick: () => void;
    onDeletePosition: (positionId: number) => void;
    deletePositionLoading: boolean;
}

function SectionCard({
    section,
    positions,
    published,
    onAddClick,
    onDeletePosition,
    deletePositionLoading,
}: SectionCardProps) {
    const [collapsed, setCollapsed] = useState(false);
    const total = positions.reduce((sum, p) => sum + p.value, 0);

    return (
        <Box
            sx={{
                border: '1px solid',
                borderColor: 'divider',
                borderRadius: 2,
                bgcolor: 'background.paper',
                overflow: 'hidden',
            }}
        >
            {/* Header */}
            <Box
                sx={{
                    display: 'flex',
                    alignItems: 'center',
                    gap: 1.5,
                    px: 2.5,
                    py: 1.5,
                    bgcolor: '#FAFAF8',
                    borderBottom: collapsed ? 'none' : '1px solid',
                    borderColor: 'divider',
                    cursor: 'pointer',
                    userSelect: 'none',
                }}
                onClick={() => setCollapsed((c) => !c)}
            >
                <Box sx={{ flex: 1, minWidth: 0 }}>
                    <Stack direction="row" alignItems="center" spacing={1} flexWrap="wrap">
                        <Typography variant="body2" fontWeight={600} sx={{ lineHeight: 1.4 }}>
                            {section.label}
                        </Typography>
                        {section.autoGenerated && (
                            <Chip
                                icon={<AutoAwesomeOutlinedIcon sx={{ fontSize: '12px !important' }} />}
                                label="Automatisch"
                                size="small"
                                variant="outlined"
                                sx={{
                                    fontSize: '0.65rem',
                                    height: 18,
                                    borderRadius: 1,
                                    color: 'text.secondary',
                                    borderColor: 'divider',
                                    '& .MuiChip-icon': { color: 'text.disabled' },
                                }}
                            />
                        )}
                    </Stack>
                </Box>
                <Typography
                    variant="body2"
                    fontWeight={700}
                    sx={{
                        flexShrink: 0,
                        color: section.isIncome
                            ? 'success.main'
                            : total > 0
                                ? 'text.primary'
                                : 'text.secondary',
                        minWidth: 80,
                        textAlign: 'right',
                    }}
                >
                    {total.toFixed(2)} €
                </Typography>
                <KeyboardArrowDownIcon
                    sx={{
                        fontSize: 18,
                        color: 'text.secondary',
                        flexShrink: 0,
                        transform: collapsed ? 'rotate(-90deg)' : 'rotate(0deg)',
                        transition: 'transform 0.2s ease',
                    }}
                />
            </Box>

            {/* Body */}
            {!collapsed && (
                <Box sx={{ px: 2.5, py: 1.5 }}>
                    {positions.length === 0 ? (
                        <Typography
                            variant="body2"
                            color="text.disabled"
                            sx={{ py: 0.5, fontStyle: 'italic' }}
                        >
                            {section.autoGenerated
                                ? 'Wird automatisch aus den Daten berechnet (Backend ausstehend)'
                                : 'Keine Positionen vorhanden'}
                        </Typography>
                    ) : (
                        <Stack divider={<Divider flexItem />}>
                            {positions.map((pos) => {
                                const canDelete = !pos.automaticallyCalculated && !published;
                                return (
                                    <Stack
                                        key={pos.id}
                                        direction="row"
                                        alignItems="center"
                                        justifyContent="space-between"
                                        sx={{ py: 0.75 }}
                                    >
                                        <Box sx={{ flex: 1, minWidth: 0, mr: 2 }}>
                                            <Typography variant="body2" noWrap>
                                                {pos.description}
                                            </Typography>
                                            {pos.automaticallyCalculated && (
                                                <Typography variant="caption" color="text.disabled">
                                                    Automatisch berechnet
                                                </Typography>
                                            )}
                                        </Box>
                                        <Stack direction="row" alignItems="center" spacing={0.5}>
                                            <Typography
                                                variant="body2"
                                                fontWeight={600}
                                                sx={{ minWidth: 70, textAlign: 'right' }}
                                            >
                                                {pos.value.toFixed(2)} €
                                            </Typography>
                                            {/* Only render delete button for manually added positions */}
                                            {!pos.automaticallyCalculated && (
                                                <Tooltip
                                                    title={
                                                        published
                                                            ? 'EÜR ist bereits veröffentlicht'
                                                            : 'Position löschen'
                                                    }
                                                >
                                                    <span>
                                                        <IconButton
                                                            size="small"
                                                            color="error"
                                                            onClick={() => onDeletePosition(pos.id!)}
                                                            disabled={published || deletePositionLoading}
                                                            aria-label="Position löschen"
                                                        >
                                                            <DeleteOutlineIcon sx={{ fontSize: 16 }} />
                                                        </IconButton>
                                                    </span>
                                                </Tooltip>
                                            )}
                                            {/* Placeholder spacing so layout stays consistent */}
                                            {pos.automaticallyCalculated && (
                                                <Box sx={{ width: 28 }} />
                                            )}
                                        </Stack>
                                    </Stack>
                                );
                            })}
                        </Stack>
                    )}

                    {!published && (
                        <Box sx={{ mt: 1.5, display: 'flex', justifyContent: 'flex-end' }}>
                            <Button
                                size="small"
                                variant="outlined"
                                startIcon={<AddIcon />}
                                onClick={(e) => {
                                    e.stopPropagation();
                                    onAddClick();
                                }}
                            >
                                Position hinzufügen
                            </Button>
                        </Box>
                    )}
                </Box>
            )}
        </Box>
    );
}

// ─── EÜR detail view ─────────────────────────────────────────────────────────

interface EuerDetailProps {
    entry: EuerReport;
    onBack: () => void;
    onEntryUpdated: (updated: EuerReport) => void;
    onEntryDeleted: () => void;
}

function EuerDetail({ entry, onBack, onEntryUpdated, onEntryDeleted }: EuerDetailProps) {
    const { handleDelete: deleteEuer, loading: deleteLoading } = useDeleteEuer();
    const { handlePublish, loading: publishLoading } = usePublishEuer();
    const { handleAdd, loading: addLoading, error: addError, setError: setAddError } = useAddEuerPosition();
    const { handleDelete: deletePosition, loading: deletePositionLoading } = useDeleteEuerPosition();

    const [addDialogSection, setAddDialogSection] = useState<EuerSection | null>(null);
    const [description, setDescription] = useState('');
    const [amount, setAmount] = useState('');
    const [deleteConfirmOpen, setDeleteConfirmOpen] = useState(false);
    const [publishConfirmOpen, setPublishConfirmOpen] = useState(false);

    const positions = entry.positions ?? [];
    const published = entry.published ?? false;

    const positionsForSection = (sectionId: EuerSection) =>
        positions.filter((p) => p.section === sectionId);

    const totalIncome = SECTIONS.filter((s) => s.isIncome).reduce(
        (sum, s) => sum + positionsForSection(s.id).reduce((a, p) => a + p.value, 0),
        0
    );
    const totalExpenses = SECTIONS.filter((s) => !s.isIncome).reduce(
        (sum, s) => sum + positionsForSection(s.id).reduce((a, p) => a + p.value, 0),
        0
    );
    const profit = totalIncome - totalExpenses;

    const handleAddSubmit = async () => {
        if (!addDialogSection) return;
        const parsedAmount = parseFloat(amount);
        if (!description.trim() || isNaN(parsedAmount) || parsedAmount < 0) return;
        const added = await handleAdd(entry.id!, addDialogSection, description.trim(), parsedAmount);
        if (added) {
            setDescription('');
            setAmount('');
            setAddDialogSection(null);
        }
    };

    const handleDeleteConfirmed = async () => {
        setDeleteConfirmOpen(false);
        const ok = await deleteEuer(entry.id!);
        if (ok) onEntryDeleted();
    };

    const handlePublishConfirmed = async () => {
        setPublishConfirmOpen(false);
        const updated = await handlePublish(entry.id!);
        if (updated) onEntryUpdated(updated);
    };

    const handleDeletePosition = async (positionId: number) => {
        await deletePosition(entry.id!, positionId);
    };

    return (
        <Stack spacing={3} width="100%">
            {/* Header */}
            <Box>
                <Stack direction="row" alignItems="center" justifyContent="space-between" flexWrap="wrap" gap={1}>
                    <Stack direction="row" alignItems="center" spacing={1.5}>
                        <Tooltip title="Zurück zur Übersicht">
                            <IconButton size="small" onClick={onBack} aria-label="Zurück">
                                <ArrowBackIcon fontSize="small" />
                            </IconButton>
                        </Tooltip>
                        <ReceiptLongIcon sx={{ color: 'primary.main', fontSize: 26 }} />
                        <Typography variant="h5">EÜR {entry.year}</Typography>
                        {published && (
                            <Chip
                                label="Veröffentlicht"
                                size="small"
                                color="success"
                                sx={{ fontWeight: 600, fontSize: '0.72rem' }}
                            />
                        )}
                    </Stack>
                    <Stack direction="row" spacing={1}>
                        {!published && (
                            <Button
                                variant="outlined"
                                color="primary"
                                size="small"
                                startIcon={publishLoading ? <CircularProgress size={14} /> : <PublishIcon />}
                                onClick={() => setPublishConfirmOpen(true)}
                                disabled={publishLoading}
                            >
                                Veröffentlichen
                            </Button>
                        )}
                        <Tooltip title={published ? 'Veröffentlichte EÜR kann nicht gelöscht werden' : 'EÜR löschen'}>
                            <span>
                                <Button
                                    variant="outlined"
                                    color="error"
                                    size="small"
                                    startIcon={deleteLoading ? <CircularProgress size={14} color="error" /> : <DeleteOutlineIcon />}
                                    onClick={() => setDeleteConfirmOpen(true)}
                                    disabled={published || deleteLoading}
                                >
                                    Löschen
                                </Button>
                            </span>
                        </Tooltip>
                    </Stack>
                </Stack>
                <Divider sx={{ mt: 2 }} />
            </Box>

            {/* Income sections */}
            <Box>
                <Typography variant="overline" color="text.secondary" sx={{ fontWeight: 600, letterSpacing: '0.08em' }}>
                    Einnahmen
                </Typography>
                <Stack spacing={1} sx={{ mt: 1 }}>
                    {SECTIONS.filter((s) => s.isIncome).map((section) => (
                        <SectionCard
                            key={section.id}
                            section={section}
                            positions={positionsForSection(section.id)}
                            published={published}
                            euerId={entry.id!}
                            onAddClick={() => setAddDialogSection(section.id)}
                            onDeletePosition={handleDeletePosition}
                            deletePositionLoading={deletePositionLoading}
                        />
                    ))}
                </Stack>
            </Box>

            {/* Expense sections */}
            <Box>
                <Typography variant="overline" color="text.secondary" sx={{ fontWeight: 600, letterSpacing: '0.08em' }}>
                    Ausgaben
                </Typography>
                <Stack spacing={1} sx={{ mt: 1 }}>
                    {SECTIONS.filter((s) => !s.isIncome).map((section) => (
                        <SectionCard
                            key={section.id}
                            section={section}
                            positions={positionsForSection(section.id)}
                            published={published}
                            euerId={entry.id!}
                            onAddClick={() => setAddDialogSection(section.id)}
                            onDeletePosition={handleDeletePosition}
                            deletePositionLoading={deletePositionLoading}
                        />
                    ))}
                </Stack>
            </Box>

            {/* Summary */}
            <Box
                sx={{
                    border: '1px solid',
                    borderColor: 'divider',
                    borderRadius: 2,
                    bgcolor: 'background.paper',
                    overflow: 'hidden',
                }}
            >
                <Box sx={{ px: 2.5, py: 1.5, bgcolor: '#FAFAF8', borderBottom: '1px solid', borderColor: 'divider' }}>
                    <Typography variant="body2" fontWeight={700}>Zusammenfassung</Typography>
                </Box>
                <Stack divider={<Divider flexItem />}>
                    <Stack direction="row" justifyContent="space-between" alignItems="center" sx={{ px: 2.5, py: 1.25 }}>
                        <Stack direction="row" alignItems="center" spacing={1}>
                            <NorthEastIcon sx={{ fontSize: 16, color: 'success.main' }} />
                            <Typography variant="body2" color="text.secondary">Gesamteinnahmen</Typography>
                        </Stack>
                        <Typography variant="body2" fontWeight={600} color="success.main">
                            {totalIncome.toFixed(2)} €
                        </Typography>
                    </Stack>
                    <Stack direction="row" justifyContent="space-between" alignItems="center" sx={{ px: 2.5, py: 1.25 }}>
                        <Stack direction="row" alignItems="center" spacing={1}>
                            <SouthEastIcon sx={{ fontSize: 16, color: 'error.main' }} />
                            <Typography variant="body2" color="text.secondary">Gesamtausgaben</Typography>
                        </Stack>
                        <Typography variant="body2" fontWeight={600} color="error.main">
                            {totalExpenses.toFixed(2)} €
                        </Typography>
                    </Stack>
                    <Stack direction="row" justifyContent="space-between" alignItems="center" sx={{ px: 2.5, py: 1.5 }}>
                        <Typography variant="body2" fontWeight={700}>
                            {profit >= 0 ? 'Gewinn' : 'Verlust'}
                        </Typography>
                        <Typography variant="body1" fontWeight={700} color={profit >= 0 ? 'success.main' : 'error.main'}>
                            {profit.toFixed(2)} €
                        </Typography>
                    </Stack>
                </Stack>
            </Box>

            {/* Add position dialog */}
            <Dialog open={addDialogSection !== null} onClose={() => { setAddDialogSection(null); setAddError(''); }} maxWidth="xs" fullWidth>
                <DialogTitle>
                    Position hinzufügen
                    {addDialogSection && (
                        <Typography variant="body2" color="text.secondary" sx={{ mt: 0.5, fontWeight: 400 }}>
                            {SECTIONS.find((s) => s.id === addDialogSection)?.label}
                        </Typography>
                    )}
                </DialogTitle>
                <DialogContent>
                    <Stack spacing={2} sx={{ mt: 1 }}>
                        {addError && <Alert severity="error" onClose={() => setAddError('')}>{addError}</Alert>}
                        <TextField
                            label="Beschreibung"
                            value={description}
                            onChange={(e) => setDescription(e.target.value)}
                            size="small"
                            fullWidth
                            required
                            autoFocus
                        />
                        <TextField
                            label="Betrag (€)"
                            value={amount}
                            onChange={(e) => setAmount(e.target.value)}
                            size="small"
                            fullWidth
                            required
                            type="number"
                            inputProps={{ min: 0, step: '0.01' }}
                        />
                    </Stack>
                </DialogContent>
                <DialogActions>
                    <Button onClick={() => { setAddDialogSection(null); setAddError(''); }}>Abbrechen</Button>
                    <Button
                        variant="contained"
                        onClick={handleAddSubmit}
                        disabled={addLoading || !description.trim() || !amount || parseFloat(amount) < 0}
                        startIcon={addLoading ? <CircularProgress size={14} color="inherit" /> : undefined}
                    >
                        Hinzufügen
                    </Button>
                </DialogActions>
            </Dialog>

            {/* Delete confirm dialog */}
            <Dialog open={deleteConfirmOpen} onClose={() => setDeleteConfirmOpen(false)} maxWidth="xs" fullWidth>
                <DialogTitle>EÜR löschen?</DialogTitle>
                <DialogContent>
                    <Typography variant="body2" color="text.secondary">
                        Die EÜR {entry.year} wird unwiderruflich gelöscht. Alle manuell erfassten Positionen gehen verloren.
                    </Typography>
                </DialogContent>
                <DialogActions>
                    <Button onClick={() => setDeleteConfirmOpen(false)}>Abbrechen</Button>
                    <Button variant="contained" color="error" onClick={handleDeleteConfirmed}>
                        Löschen
                    </Button>
                </DialogActions>
            </Dialog>

            {/* Publish confirm dialog */}
            <Dialog open={publishConfirmOpen} onClose={() => setPublishConfirmOpen(false)} maxWidth="xs" fullWidth>
                <DialogTitle>EÜR veröffentlichen?</DialogTitle>
                <DialogContent>
                    <Typography variant="body2" color="text.secondary">
                        Die EÜR {entry.year} wird veröffentlicht. Danach können keine Positionen mehr hinzugefügt oder gelöscht werden.
                    </Typography>
                </DialogContent>
                <DialogActions>
                    <Button onClick={() => setPublishConfirmOpen(false)}>Abbrechen</Button>
                    <Button variant="contained" onClick={handlePublishConfirmed}>
                        Veröffentlichen
                    </Button>
                </DialogActions>
            </Dialog>
        </Stack>
    );
}

